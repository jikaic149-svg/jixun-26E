#ifndef ALGORITHM_PACKET_H
#define ALGORITHM_PACKET_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

/* The canonical transmitted frame, including its LF terminator, is at most
 * 128 bytes. A received CRLF frame is subject to the same physical limit.
 */
#define ALGORITHM_PACKET_MAX_FRAME_SIZE 128U
#define ALGORITHM_PACKET_PARSER_STORAGE_SIZE \
    (ALGORITHM_PACKET_MAX_FRAME_SIZE - 1U)
#define ALGORITHM_PACKET_MAX_TYPE_LENGTH 16U
#define ALGORITHM_PACKET_MAX_PAYLOAD_LENGTH 111U

typedef enum {
    ALGORITHM_PACKET_ENCODE_OK = 0,
    ALGORITHM_PACKET_ENCODE_INVALID_ARGUMENT,
    ALGORITHM_PACKET_ENCODE_INVALID_TYPE,
    ALGORITHM_PACKET_ENCODE_INVALID_PAYLOAD,
    ALGORITHM_PACKET_ENCODE_FRAME_TOO_LONG,
    ALGORITHM_PACKET_ENCODE_OUTPUT_TOO_SMALL
} Algorithm_Packet_EncodeResult;

/* A zero-copy view into a parser's caller-owned storage. Neither slice is
 * NUL-terminated. It remains valid only until the next Parser_Feed() call on
 * the same parser.
 */
typedef struct {
    const uint8_t *type;
    size_t type_length;
    uint16_t sequence;
    const uint8_t *payload;
    size_t payload_length;
} Algorithm_Packet_View;

typedef enum {
    ALGORITHM_PACKET_ERROR_NONE = 0,
    ALGORITHM_PACKET_ERROR_INVALID_START,
    ALGORITHM_PACKET_ERROR_FRAME_TOO_LONG,
    ALGORITHM_PACKET_ERROR_INVALID_FORMAT,
    ALGORITHM_PACKET_ERROR_UNSUPPORTED_VERSION,
    ALGORITHM_PACKET_ERROR_INVALID_TYPE,
    ALGORITHM_PACKET_ERROR_INVALID_SEQUENCE,
    ALGORITHM_PACKET_ERROR_INVALID_LENGTH,
    ALGORITHM_PACKET_ERROR_INVALID_PAYLOAD,
    ALGORITHM_PACKET_ERROR_CRC_MISMATCH
} Algorithm_Packet_Error;

typedef enum {
    ALGORITHM_PACKET_FEED_IN_PROGRESS = 0,
    ALGORITHM_PACKET_FEED_FRAME_READY,
    ALGORITHM_PACKET_FEED_FRAME_REJECTED,
    ALGORITHM_PACKET_FEED_INVALID_ARGUMENT
} Algorithm_Packet_FeedResult;

/* Each parser instance owns only stream state. Frame bytes live in storage,
 * which is supplied and retained by the caller. The structure and storage
 * must be used by one serialized consumer; Parser_Feed() is not re-entrant.
 */
typedef struct {
    uint8_t *storage;
    size_t storage_capacity;
    size_t length;
    uint32_t accepted_count;
    uint32_t error_count;
    Algorithm_Packet_Error last_error;
    bool discarding;
} Algorithm_Packet_Parser;

/* CRC-16/CCITT-FALSE: poly 0x1021, init 0xFFFF, refin/refout false,
 * xorout 0x0000. bytes must be non-null when length is nonzero.
 */
uint16_t Algorithm_Packet_Crc16CcittFalse(
    const uint8_t *bytes, size_t length);

/* Encode exactly:
 *     @1|TYPE|SEQ|LEN|PAYLOAD|CRC16\n
 *
 * CRC16 is four uppercase hexadecimal digits. The CRC covers every byte from
 * '@' through the '|' immediately before the CRC digits (both included).
 * TYPE must match [A-Z][A-Z0-9_]{0,15}. SEQ and LEN use canonical unsigned
 * decimal without leading zeroes. PAYLOAD is printable ASCII 0x20..0x7E.
 *
 * output_length is required and is set to zero for ordinary validation
 * failures. On OUTPUT_TOO_SMALL it receives the required size; on success it
 * receives the encoded size. No output byte is written unless the complete
 * frame fits. output and payload must not overlap.
 */
Algorithm_Packet_EncodeResult Algorithm_Packet_Encode(
    const char *type,
    uint16_t sequence,
    const uint8_t *payload,
    size_t payload_length,
    uint8_t *output,
    size_t output_capacity,
    size_t *output_length);

/* storage_capacity must be at least ALGORITHM_PACKET_PARSER_STORAGE_SIZE.
 * Larger buffers are accepted but the protocol limit remains 128 bytes.
 */
bool Algorithm_Packet_Parser_Init(
    Algorithm_Packet_Parser *parser,
    uint8_t *storage,
    size_t storage_capacity);

/* Reset partial input, counters, and last error without changing storage. */
void Algorithm_Packet_Parser_Reset(Algorithm_Packet_Parser *parser);

/* Feed one received byte. LF terminates a frame; one immediately preceding CR
 * is tolerated and removed. Transmitters generated by Encode() use LF only.
 *
 * A wire error is counted once and returns FRAME_REJECTED. When an error is
 * detected before LF, subsequent bytes are discarded through the next LF;
 * parsing then resumes. INVALID_ARGUMENT is an API misuse and is not counted.
 */
Algorithm_Packet_FeedResult Algorithm_Packet_Parser_Feed(
    Algorithm_Packet_Parser *parser,
    uint8_t byte,
    Algorithm_Packet_View *packet);

uint32_t Algorithm_Packet_Parser_AcceptedCount(
    const Algorithm_Packet_Parser *parser);
uint32_t Algorithm_Packet_Parser_ErrorCount(
    const Algorithm_Packet_Parser *parser);
Algorithm_Packet_Error Algorithm_Packet_Parser_LastError(
    const Algorithm_Packet_Parser *parser);

#endif
